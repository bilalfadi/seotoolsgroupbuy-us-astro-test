/**
 * Generate Cloudflare Workers Static Assets / Pages real HTTP 301 redirects.
 * All imported legacy slugs are grounded in src/lib/route-fixes.js.
 * Keep old routes out of Astro getStaticPaths so no meta-refresh assets shadow rules.
 */
import fs from 'node:fs';
import path from 'node:path';
import {redirects} from '../src/lib/route-fixes.js';
import {load} from '../src/lib/content.js';
const existingSlugs=new Set([...load('products'),...load('posts'),...load('pages')].map(x=>x.slug));
const rules=new Map();
function add(from,to){
  if(!from.startsWith('/')||!to.startsWith('/')||from===to)throw new Error('Invalid redirect '+from+' => '+to);
  if(rules.has(from)&&rules.get(from)!==to)throw new Error('Conflicting redirect '+from);
  rules.set(from,to);
}
// Historical WordPress archive/tag links (previously hardcoded in public/_redirects).
add('/blog/','/category/seo-tools-blog/');
add('/product-tag/buy-cheap-ahrefs/','/ahrefs/');
add('/product-tag/moz-pro-group-buy/','/moz/');
for(const [oldSlug,newSlug] of Object.entries(redirects)){
  if(existingSlugs.has(oldSlug))throw new Error('Redirect shadows a published page: '+oldSlug);
  add('/'+oldSlug+'/','/'+newSlug+'/');
}
for(const [from,to] of rules) {
  if(!to.startsWith('/category/') && !existingSlugs.has(to.slice(1,-1)))
    throw new Error('Redirect target is not published: '+from+' => '+to);
}
if(rules.size>2000)throw new Error('Cloudflare static _redirects exceeds 2000 rules');
const lines=[...rules.entries()].sort(([a],[b])=>a.localeCompare(b)).map(([from,to])=>from+' '+to+' 301');
fs.writeFileSync(path.join(process.cwd(),'public','_redirects'), '# Cloudflare Workers / Pages HTTP 301 rules; generated by scripts/generate-redirects.mjs\n'+lines.join('\n')+'\n');
console.log('REDIRECTS_COUNT='+lines.length);
console.log('REDIRECT_MAP_START');
for(const line of lines)console.log(line);
console.log('REDIRECT_MAP_END');
